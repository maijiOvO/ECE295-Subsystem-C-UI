static void Write_Cmd(uint8_t addr, uint8_t cmd) {
    twi_start();
    twi_MT_SLA_W(addr);
    twi_MT_write(0x00); 
    twi_MT_write(cmd);
    twi_stop();
}

static void Write_Data(uint8_t addr, uint8_t data) {
    twi_start();
    twi_MT_SLA_W(addr);
    twi_MT_write(0x40); 
    twi_MT_write(data);
    twi_stop();
}
void OLED_Init(uint8_t addr) {
    Write_Cmd(addr, 0xAE);
    Write_Cmd(addr, 0xD5); Write_Cmd(addr, 0x80);
    Write_Cmd(addr, 0xA8); Write_Cmd(addr, 0x3F);
    Write_Cmd(addr, 0xD3); Write_Cmd(addr, 0x00);
    Write_Cmd(addr, 0x40);
    Write_Cmd(addr, 0x8D); Write_Cmd(addr, 0x14);
    Write_Cmd(addr, 0x20); Write_Cmd(addr, 0x00);
    Write_Cmd(addr, 0xA0); Write_Cmd(addr, 0xC0);// flip the screen
    Write_Cmd(addr, 0xDA); Write_Cmd(addr, 0x12);
    Write_Cmd(addr, 0x81); Write_Cmd(addr, 0xCF);
    Write_Cmd(addr, 0xD9); Write_Cmd(addr, 0xF1);
    Write_Cmd(addr, 0xDB); Write_Cmd(addr, 0x40);
    Write_Cmd(addr, 0xA4); Write_Cmd(addr, 0xA6);
    Write_Cmd(addr, 0xAF);
}

void OLED_Fill(uint8_t addr, uint8_t data) {
    Write_Cmd(addr, 0x21); Write_Cmd(addr, 0); Write_Cmd(addr, 127);
    Write_Cmd(addr, 0x22); Write_Cmd(addr, 0); Write_Cmd(addr, 7);
    
    twi_start();
    twi_MT_SLA_W(addr);
    twi_MT_write(0x40);
    for (int i = 0; i < 1024; i++) {
        twi_MT_write(data);
    }
    twi_stop();
}

void OLED_Clear(uint8_t addr) {
    OLED_Fill(addr, 0x00);
}

void OLED_SetPos(uint8_t addr, uint8_t x, uint8_t y) {
    Write_Cmd(addr, 0xB0 + y);
    Write_Cmd(addr, 0x00 + (x & 0x0F));
    Write_Cmd(addr, 0x10 + ((x >> 4) & 0x0F));
}

void OLED_ShowChar(uint8_t addr, uint8_t x, uint8_t y, char chr, uint8_t mode) {
    uint8_t c = chr - 32;
    if(c > 95) return;
    
    OLED_SetPos(addr, x, y);
    twi_start();
    twi_MT_SLA_W(addr);
    twi_MT_write(0x40);
    
    for(uint8_t i = 0; i < 6; i++) {
        uint8_t byte = F6x8[c][i];
        if(mode == OLED_MODE_INVERT) {
            byte = ~byte; 
        }
        twi_MT_write(byte);
    }
    twi_stop();
}

void OLED_ShowString(uint8_t addr, uint8_t x, uint8_t y, char *str, uint8_t mode) {
    uint8_t j = 0;
    while (str[j] != '\0') {
        OLED_ShowChar(addr, x, y, str[j], mode);
        x += 6;
        if(x > 120) { x = 0; y++; }
        j++;
    }
}
// 1. pixels (1KB)
static uint8_t OLED_Buffer[1024]; 

// 2. clear screen
void OLED_Clear_Buffer() {
    for(int i=0; i<1024; i++) {
        OLED_Buffer[i] = 0x00;
    }
}


void OLED_Buffer_ShowChar(int x, int y, char chr) {
    int c = chr - 32;
    if(c > 95) return;
    
    for(int i=0; i<6; i++) {
        if(x+i < 128) {
            OLED_Buffer[y * 128 + (x + i)] = F6x8[c][i];
        }
    }
}

void OLED_Update(uint8_t addr) {
    Write_Cmd(addr, 0x21); Write_Cmd(addr, 0); Write_Cmd(addr, 127);
    Write_Cmd(addr, 0x22); Write_Cmd(addr, 0); Write_Cmd(addr, 7);
    
    twi_start();
    twi_MT_SLA_W(addr);
    twi_MT_write(0x40);
    
    for(int i=0; i<1024; i++) {
        twi_MT_write(OLED_Buffer[i]);
    }
    twi_stop();
}

void OLED_Sleep(uint8_t addr) {
    Write_Cmd(addr, 0xAE);  // Display OFF
    Write_Cmd(addr, 0x8D);  // Charge Pump
    Write_Cmd(addr, 0x10);  // Disable Charge Pump
}

void OLED_Wake(uint8_t addr) {
    Write_Cmd(addr, 0x8D);  // Charge Pump
    Write_Cmd(addr, 0x14);  // Enable Charge Pump
    Write_Cmd(addr, 0xAF);  // Display ON
}
